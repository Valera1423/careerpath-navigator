STAR_MARKERS: dict[str, list[str]] = {
    "situation": [r"\b(когда|ситуаци|проект|команд|задач|проблем)\b"],
    "task": [r"\b(нужно было|требовалось|цель|задач|стоял)\b"],
    "action": [r"\b(я сделал|решил|реализовал|написал|провёл|предложил|разработал)\b"],
    "result": [r"\b(в итоге|результат|удалось|получилось|вырос|сократил|улучшил|повысил)\b"],
}


@dataclass
class StarScore:
    situation: bool
    task: bool
    action: bool
    result: bool
    score: int
    feedback: str


def questions_for(position: str, limit: int = 5) -> list[str]:
    family = detect_role_family(position)
    pool = QUESTION_BANK.get(family, QUESTION_BANK["generic"])
    return pool[:limit]


def evaluate_answer(answer: str) -> StarScore:
    text = answer.lower()
    hits = {
        key: any(re.search(p, text) for p in patterns)
        for key, patterns in STAR_MARKERS.items()
    }
    count = sum(hits.values())
    score = int(round(count / 4 * 10))

    tips: list[str] = []
    if not hits["situation"]:
        tips.append("Опиши контекст: где, когда, с кем")
    if not hits["task"]:
        tips.append("Сформулируй задачу: что нужно было сделать")
    if not hits["action"]:
        tips.append("Опиши свои действия: что именно сделал ТЫ")
    if not hits["result"]:
        tips.append("Добавь результат: цифры, эффект, вывод")

    feedback = "Отличная структура!" if score >= 8 else "Улучши: " + "; ".join(tips)
    return StarScore(**hits, score=score, feedback=feedback)