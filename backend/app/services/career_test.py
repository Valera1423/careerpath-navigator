@dataclass
class CareerTestResult:
    scores: dict[str, int]
    top_type: str
    professions: list[str]
    description: str


def evaluate(answers: dict[int, int]) -> CareerTestResult:
    """answers: {question_id: 0..2} где 0 = нет, 2 = да."""
    scores = {t: 0 for t in TYPE_TO_PROFESSIONS}
    for q in QUESTIONS:
        scores[q["type"]] += answers.get(q["id"], 0)

    top = max(scores, key=lambda k: scores[k])
    return CareerTestResult(
        scores=scores,
        top_type=top,
        professions=TYPE_TO_PROFESSIONS[top],
        description=TYPE_DESCRIPTION[top],
    )


def list_questions() -> list[dict]:
    return QUESTIONS


def day_in_life(profession: str) -> list[str] | None:
    for name, timeline in DAY_IN_LIFE.items():
        if profession.lower() in name.lower():
            return timeline
    return None